PHASE2_TP = _cfg.PHASE2_TP                  # 4.0
PHASE2_SL = _cfg.PHASE2_SL                  # 2.0
PHASE2_CAPITAL_PCT = _cfg.PHASE2_CAPITAL_PCT  # 50.0
MIN_CONDITIONS = _cfg.MIN_CONDITIONS          # 2
MAX_CONDITIONS = _cfg.MAX_CONDITIONS          # 5


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _make_feature_infos(modes: list[str]) -> list[dict]:
    """Create a minimal feature_infos list from a list of mode strings."""
    return [{"name": f"feat_{i}", "mode": m, "score": 0.5} for i, m in enumerate(modes)]


def _make_train_df(
    n_rows: int,
    n_features: int,
    symbols: list[str],
    seed: int = 42,
) -> pd.DataFrame:
    """
    Build a minimal training DataFrame with all required label columns and
    integer-valued feature columns (0–4, matching 'positive' mode).
    """
    rng = np.random.default_rng(seed)
    rows_per_sym = max(1, n_rows // len(symbols))
    dfs = []
    for sym in symbols:
        n = rows_per_sym
        open_next = rng.uniform(100.0, 200.0, size=n)
        max_288 = open_next * rng.uniform(0.98, 1.10, size=n)
        min_288 = open_next * rng.uniform(0.90, 1.02, size=n)
        close_288 = open_next * rng.uniform(0.95, 1.05, size=n)
        max_before_min = rng.integers(0, 2, size=n).astype(float)

        data: dict = {
            "datetime": pd.date_range("2024-01-01", periods=n, freq="5min"),
            "symbol": sym,
            "label_open_next": open_next,
            "label_close_288": close_288,
            "label_min_288": min_288,
            "label_max_288": max_288,
            "label_max_before_min": max_before_min,
            "_symbol_bar_index": np.arange(n),
        }
        for i in range(n_features):
            data[f"feat_{i}"] = rng.integers(0, 5, size=n).astype(float)

        dfs.append(pd.DataFrame(data))

    return pd.concat(dfs, ignore_index=True)


