# ---------------------------------------------------------------------------
# Mock engine that records every simulate_rule_batch call
# ---------------------------------------------------------------------------

class _RecordingEngine:
    """
    Drop-in replacement for GPUBacktestEngine / CPUBacktestEngine.

    Records every call to simulate_rule_batch so tests can assert that
    the static Phase 2 risk parameters were used.
    """

    def __init__(self):
        self.calls: list[dict] = []

    def simulate_rule_batch(
        self,
        chromosomes: np.ndarray,
        tp: float,
        sl: float,
        capital_pct: float,
        **kwargs,
    ) -> list[dict]:
        self.calls.append({"tp": tp, "sl": sl, "capital_pct": capital_pct})
        # Return a plausible metrics dict for each chromosome in the batch
        return [
            {
                "sortino_ratio": 1.0,
                "total_return_pct": 1.0,
                "max_drawdown_pct": 0.5,
                "win_rate": 55.0,
                "executed_trades": 25,
            }
            for _ in range(len(chromosomes))
        ]


